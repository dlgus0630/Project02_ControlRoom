/* printf를 USART1(ST-Link 가상 시리얼포트)로 내보내는 함수.
   관리실 입장/퇴장 로그(app_control_room_fsm.c의 log_event())가 이걸 통해 찍힌다. */
int __io_putchar(int ch)
{
    if (ch == '\n')
        HAL_UART_Transmit(&huart1, (uint8_t *)"\r", 1, 0xFFFF);
    HAL_UART_Transmit(&huart1, (uint8_t *)&ch, 1, 0xFFFF);
    return ch;
}

